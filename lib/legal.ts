export function isLegalDocId(v: unknown): v is LegalDocId {
  return v === 'terms' || v === 'privacy';
}

/** 아직 채우지 않은 [자리표시]가 남아 있는지 (출시 전 점검용) */
export function legalPlaceholders(): string[] {
  const text = JSON.stringify(LEGAL_DOCS);
  return [...new Set(text.match(/\[[^\]\[]{2,30}\]/g) ?? [])].filter((m) => !m.startsWith('[내 정보'));
}
